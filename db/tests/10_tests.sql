  ------------------------------------------------------------------
  -- Ledger integrity: stored balance must equal the ledger, always.
  ------------------------------------------------------------------
  procedure test_reconciliation is
    l_disc number;
  begin
    pkg_security.set_context('MANAGER');
    pkg_sample.reconcile_balances(l_disc);
    assert_equals('LEDGER', 'Stored balances match the transaction ledger', 0, l_disc);
  end test_reconciliation;

  ------------------------------------------------------------------
  procedure run_all is
  begin
    delete from test_results;
    commit;

    begin test_samples;        exception when others then log_result('SAMPLES','suite aborted','SHOULD_PASS',false,sqlerrm); end;
    begin test_overlap;        exception when others then log_result('OVERLAP','suite aborted','SHOULD_PASS',false,sqlerrm); end;
    begin test_plan_states;    exception when others then log_result('PLAN','suite aborted','SHOULD_PASS',false,sqlerrm); end;
    begin test_scoping;        exception when others then log_result('SCOPE','suite aborted','SHOULD_PASS',false,sqlerrm); end;
    begin test_period_lock;    exception when others then log_result('PERIOD','suite aborted','SHOULD_PASS',false,sqlerrm); end;
    begin test_reconciliation; exception when others then log_result('LEDGER','suite aborted','SHOULD_PASS',false,sqlerrm); end;

    commit;
    report;
  end run_all;

  ------------------------------------------------------------------
  procedure report is
    l_total number; l_passed number;
  begin
    select count(*), count(case when passed = 'Y' then 1 end)
      into l_total, l_passed
      from test_results;

    dbms_output.put_line(rpad('-', 78, '-'));
    dbms_output.put_line('Pharma Visit System business rule suite');
    dbms_output.put_line(rpad('-', 78, '-'));

    for r in (select suite, test_name, expectation, passed, detail
                from test_results order by suite, result_id) loop
      dbms_output.put_line(
        rpad(case when r.passed = 'Y' then '[PASS]' else '[FAIL]' end, 8) ||
        rpad(r.suite, 10) || r.test_name);
      if r.passed = 'N' then
        dbms_output.put_line(rpad(' ', 18) || '-> ' || r.detail);
      end if;
    end loop;

    dbms_output.put_line(rpad('-', 78, '-'));
    dbms_output.put_line('Result: ' || l_passed || '/' || l_total || ' passed');

    if l_passed < l_total then
      dbms_output.put_line('SUITE FAILED');
    end if;
  end report;

end pkg_test;
