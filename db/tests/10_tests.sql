--------------------------------------------------------------------------------
-- Pharma Visit System — 10_tests.sql
-- Business rule test harness.
--
-- Why not utPLSQL
--   utPLSQL is the right choice on a real project and I would use it there.
--   For a repository meant to be cloned and run in one command, a zero-
--   dependency harness means a reviewer sees results without installing
--   anything first. The assertion style is deliberately utPLSQL-shaped so
--   migrating is mechanical.
--
-- Every business rule gets BOTH cases:
--   the negative case proves the rule blocks what it should,
--   the positive case proves it does not block what it should not.
--   A suite with only negative cases hides over-blocking bugs.
--------------------------------------------------------------------------------
set define off
set serveroutput on size unlimited

begin execute immediate 'drop table test_results purge'; exception when others then null; end;
/
create table test_results (
  result_id  number generated by default on null as identity
             constraint test_results_pk primary key,
  suite      varchar2(60)  not null,
  test_name  varchar2(200) not null,
  expectation varchar2(20) not null,
  passed     varchar2(1)   not null,
  detail     varchar2(600),
  run_on     timestamp with local time zone default systimestamp not null,
  constraint test_res_ck_pass check (passed in ('Y','N')),
  constraint test_res_ck_exp  check (expectation in ('SHOULD_PASS','SHOULD_FAIL'))
);

create or replace package pkg_test as
  procedure assert_raises (
    p_suite in varchar2, p_test in varchar2,
    p_expected_code in number, p_actual_code in number, p_detail in varchar2 default null);

  procedure assert_true (
    p_suite in varchar2, p_test in varchar2, p_condition in boolean, p_detail in varchar2 default null);

  procedure assert_equals (
    p_suite in varchar2, p_test in varchar2, p_expected in number, p_actual in number);

  procedure run_all;
  procedure report;
end pkg_test;
/

create or replace package body pkg_test as

  ------------------------------------------------------------------
  procedure log_result (
    p_suite in varchar2, p_test in varchar2,
    p_expectation in varchar2, p_passed in boolean, p_detail in varchar2) is
    pragma autonomous_transaction;
  begin
    insert into test_results (suite, test_name, expectation, passed, detail)
         values (p_suite, p_test, p_expectation,
                 case when p_passed then 'Y' else 'N' end, substr(p_detail, 1, 600));
    commit;
  end log_result;

  ------------------------------------------------------------------
  procedure assert_raises (
    p_suite in varchar2, p_test in varchar2,
    p_expected_code in number, p_actual_code in number, p_detail in varchar2 default null) is
  begin
    log_result(p_suite, p_test, 'SHOULD_FAIL',
               p_actual_code = -p_expected_code,
               'expected ORA-' || p_expected_code || ', got ' || nvl(to_char(p_actual_code), 'no error') ||
               case when p_detail is not null then ' | ' || p_detail end);
  end assert_raises;

  ------------------------------------------------------------------
  procedure assert_true (
    p_suite in varchar2, p_test in varchar2, p_condition in boolean, p_detail in varchar2 default null) is
  begin
    log_result(p_suite, p_test, 'SHOULD_PASS', nvl(p_condition, false), p_detail);
  end assert_true;

  ------------------------------------------------------------------
  procedure assert_equals (
    p_suite in varchar2, p_test in varchar2, p_expected in number, p_actual in number) is
  begin
    log_result(p_suite, p_test, 'SHOULD_PASS',
               nvl(p_expected = p_actual, false),
               'expected ' || p_expected || ', got ' || nvl(to_char(p_actual), 'null'));
  end assert_equals;

  ------------------------------------------------------------------
  -- Fixture: an isolated rep, doctor, product, batch and open period.
  -- Tests never depend on seed data, so the suite is repeatable and does
  -- not break when the seed changes.
  ------------------------------------------------------------------
  procedure fixture (
    o_rep out number, o_doctor out number, o_product out number,
    o_batch out number, o_period out number) is
  begin
    select user_id into o_rep from app_users where username = 'REP01';

    select d.doctor_id into o_doctor
      from doctors d where d.tier = 'C' and rownum = 1;

    select p.product_id into o_product
      from products p where p.status = 'ACTIVE' and rownum = 1;

    select b.batch_id into o_batch
      from product_batches b
     where b.product_id = o_product
       and b.expiry_date > add_months(sysdate, 6)
       and rownum = 1;

    -- فترة اختبار مستقلة: لا تتعارض مع بيانات البذرة
    begin
      select period_id into o_period
        from periods where period_year = 2099 and period_month = 12;
    exception when no_data_found then
      insert into periods (period_year, period_month, start_date, end_date, status)
           values (2099, 12, date '2099-12-01', date '2099-12-31', 'OPEN')
        returning period_id into o_period;
    end;
  end fixture;

  ------------------------------------------------------------------
  -- BR-03 / BR-04 / BR-05 — sample dispensing
  ------------------------------------------------------------------
  procedure test_samples is
    l_rep number; l_doc number; l_prod number; l_batch number; l_period number;
    l_trx number; l_before number; l_after number; l_remaining number;
    l_expired_batch number; l_visit number;
  begin
    fixture(l_rep, l_doc, l_prod, l_batch, l_period);
    pkg_security.set_context('MANAGER');

    -- زيارة اختبار: قيد SAMPLE_TRX_CK_DISP يشترط زيارة وطبيبًا لكل صرف
    insert into visits (rep_user_id, doctor_id, period_id, actual_start, actual_end,
                        outcome, is_unplanned, reason)
         values (l_rep, l_doc, l_period, systimestamp - interval '2' hour,
                 systimestamp - interval '1' hour, 'COMPLETED', 'Y', 'test fixture')
      returning visit_id into l_visit;

    -- Ensure stock exists for the test
    pkg_sample.receive(l_rep, l_batch, 100, 'test fixture', l_trx);
    l_before := pkg_sample.balance_of(l_rep, l_batch);

    ---------------------------------------------------------------- positive
    begin
      pkg_sample.dispense(l_rep, l_batch, l_visit, l_doc, 2, 'TEST-' || l_trx, l_trx);
      l_after := pkg_sample.balance_of(l_rep, l_batch);
      assert_equals('SAMPLES', 'BR-03 valid dispense reduces balance by exact quantity',
                    l_before - 2, l_after);
    exception
      when others then
        assert_true('SAMPLES', 'BR-03 valid dispense succeeds', false, sqlerrm);
    end;

    ---------------------------------------------------------- negative: stock
    begin
      pkg_sample.dispense(l_rep, l_batch, l_visit, l_doc, 999999, null, l_trx);
      assert_raises('SAMPLES', 'BR-03 dispense above balance is rejected', 20006, null);
    exception
      when others then
        assert_raises('SAMPLES', 'BR-03 dispense above balance is rejected', 20006, sqlcode);
    end;

    -------------------------------------------------------- negative: ceiling
    l_remaining := pkg_sample.remaining_allowance(l_doc, l_prod, l_period);
    begin
      pkg_sample.dispense(l_rep, l_batch, l_visit, l_doc, l_remaining + 1, null, l_trx);
      assert_raises('SAMPLES', 'BR-04 dispense above monthly ceiling is rejected', 20007, null);
    exception
      when others then
        assert_raises('SAMPLES', 'BR-04 dispense above monthly ceiling is rejected', 20007, sqlcode);
    end;

    ------------------------------------------------- positive: exactly at cap
    begin
      -- طبيب مستقل: سقفه كامل لم يُستهلك منه شيء في هذه المجموعة
      declare
        l_doc2   number;
        l_visit2 number;
      begin
        select doctor_id into l_doc2
          from doctors where tier = 'C' and doctor_id <> l_doc and rownum = 1;

        insert into visits (rep_user_id, doctor_id, period_id, actual_start, actual_end,
                            outcome, is_unplanned, reason)
             values (l_rep, l_doc2, l_period, systimestamp - interval '4' hour,
                     systimestamp - interval '3' hour, 'COMPLETED', 'Y', 'cap test')
          returning visit_id into l_visit2;

        l_remaining := pkg_sample.remaining_allowance(l_doc2, l_prod, l_period);
        if l_remaining > 0 then
          pkg_sample.dispense(l_rep, l_batch, l_visit2, l_doc2, l_remaining, 'TEST-CAP-' || l_rep, l_trx);
          assert_true('SAMPLES', 'BR-04 dispense exactly at the ceiling is allowed', true);
        end if;
      end;
    exception
      when others then
        assert_true('SAMPLES', 'BR-04 dispense exactly at the ceiling is allowed', false, sqlerrm);
    end;

    -------------------------------------------------------- negative: expired
    begin
      select batch_id into l_expired_batch
        from product_batches
       where expiry_date <= trunc(sysdate) and rownum = 1;

      pkg_sample.dispense(l_rep, l_expired_batch, null, l_doc, 1, null, l_trx);
      assert_raises('SAMPLES', 'BR-05 expired batch cannot be dispensed', 20008, null);
    exception
      when others then
        assert_raises('SAMPLES', 'BR-05 expired batch cannot be dispensed', 20008, sqlcode);
    end;

    -------------------------------------------------- negative: zero quantity
    begin
      pkg_sample.dispense(l_rep, l_batch, l_visit, l_doc, 0, null, l_trx);
      assert_raises('SAMPLES', 'Zero quantity is rejected', 20012, null);
    exception
      when others then
        assert_raises('SAMPLES', 'Zero quantity is rejected', 20012, sqlcode);
    end;

    ------------------------------------------------------ idempotency of sync
    declare
      l_ref  varchar2(64) := 'TEST-IDEM-' || to_char(systimestamp, 'SSSSSFF');
      l_id1  number; l_id2 number;
      l_bal1 number; l_bal2 number;
    begin
      pkg_sample.dispense(l_rep, l_batch, l_visit, l_doc, 1, l_ref, l_id1);
      l_bal1 := pkg_sample.balance_of(l_rep, l_batch);
      pkg_sample.dispense(l_rep, l_batch, l_visit, l_doc, 1, l_ref, l_id2);
      l_bal2 := pkg_sample.balance_of(l_rep, l_batch);

      assert_true('SAMPLES', 'Replayed client_ref does not dispense twice',
                  l_id1 = l_id2 and l_bal1 = l_bal2,
                  'trx ' || l_id1 || '/' || l_id2 || ', balance ' || l_bal1 || '/' || l_bal2);
    exception
      when others then
        assert_true('SAMPLES', 'Replayed client_ref does not dispense twice', false, sqlerrm);
    end;

    rollback;
  end test_samples;

  ------------------------------------------------------------------
  -- BR-01 — visit overlap
  ------------------------------------------------------------------
  procedure test_overlap is
    l_rep number; l_doc number; l_prod number; l_batch number; l_period number;
    l_plan number; l_item1 number; l_item2 number;
    l_start timestamp with local time zone;
  begin
    fixture(l_rep, l_doc, l_prod, l_batch, l_period);
    pkg_security.set_context('MANAGER');

    l_start := cast(trunc(sysdate) + 10 as timestamp) + numtodsinterval(9, 'hour');
    l_plan  := pkg_plan.get_or_create_plan(l_rep, l_period);

    ---------------------------------------------------------------- positive
    begin
      pkg_plan.add_item(l_plan, l_doc, l_start, l_start + numtodsinterval(30, 'minute'),
                        'test', l_item1);
      assert_true('OVERLAP', 'BR-01 non-overlapping item is accepted', true);
    exception
      when others then
        assert_true('OVERLAP', 'BR-01 non-overlapping item is accepted', false, sqlerrm);
    end;

    ---------------------------------------------------------------- negative
    begin
      pkg_plan.add_item(l_plan, l_doc,
                        l_start + numtodsinterval(15, 'minute'),
                        l_start + numtodsinterval(45, 'minute'),
                        'overlapping', l_item2);
      assert_raises('OVERLAP', 'BR-01 overlapping item is rejected', 20015, null);
    exception
      when others then
        assert_raises('OVERLAP', 'BR-01 overlapping item is rejected', 20015, sqlcode);
    end;

    -------------------------------------- positive: adjacent, not overlapping
    begin
      pkg_plan.add_item(l_plan, l_doc,
                        l_start + numtodsinterval(30, 'minute'),
                        l_start + numtodsinterval(60, 'minute'),
                        'adjacent', l_item2);
      assert_true('OVERLAP', 'BR-01 back-to-back visits are allowed (touching is not overlapping)', true);
    exception
      when others then
        assert_true('OVERLAP', 'BR-01 back-to-back visits are allowed', false, sqlerrm);
    end;

    rollback;
  end test_overlap;

  ------------------------------------------------------------------
  -- BR-02 — plan state machine
  ------------------------------------------------------------------
  procedure test_plan_states is
    l_rep number; l_doc number; l_prod number; l_batch number; l_period number;
    l_plan number; l_item number;
    l_start timestamp with local time zone;
  begin
    fixture(l_rep, l_doc, l_prod, l_batch, l_period);
    pkg_security.set_context('MANAGER');

    l_start := cast(trunc(sysdate) + 20 as timestamp) + numtodsinterval(11, 'hour');
    l_plan  := pkg_plan.get_or_create_plan(l_rep, l_period);
    pkg_plan.add_item(l_plan, l_doc, l_start, l_start + numtodsinterval(30,'minute'), 'test', l_item);

    -------------------------------------------- negative: approve before submit
    begin
      pkg_plan.approve(l_plan);
      assert_raises('PLAN', 'BR-02 approving a DRAFT plan is rejected', 20014, null);
    exception
      when others then
        assert_raises('PLAN', 'BR-02 approving a DRAFT plan is rejected', 20014, sqlcode);
    end;

    ------------------------------------------------- positive: submit, approve
    begin
      pkg_plan.submit(l_plan);
      pkg_plan.approve(l_plan);
      assert_true('PLAN', 'BR-02 DRAFT to SUBMITTED to APPROVED is allowed', true);
    exception
      when others then
        assert_true('PLAN', 'BR-02 DRAFT to SUBMITTED to APPROVED is allowed', false, sqlerrm);
    end;

    ------------------------------------------ negative: edit an approved plan
    begin
      pkg_plan.add_item(l_plan, l_doc,
                        l_start + numtodsinterval(3,'hour'),
                        l_start + numtodsinterval(4,'hour'), 'late add', l_item);
      assert_raises('PLAN', 'BR-02 approved plan cannot be edited directly', 20013, null);
    exception
      when others then
        assert_raises('PLAN', 'BR-02 approved plan cannot be edited directly', 20013, sqlcode);
    end;

    ------------------------------------------- negative: reject without reason
    begin
      pkg_plan.reject(l_plan, null);
      assert_raises('PLAN', 'Rejection without a reason is refused', 20016, null);
    exception
      when others then
        assert_raises('PLAN', 'Rejection without a reason is refused', 20016, sqlcode);
    end;

    rollback;
  end test_plan_states;

  ------------------------------------------------------------------
  -- BR-06 — data scoping
  ------------------------------------------------------------------
  procedure test_scoping is
    l_rep_rows number; l_mgr_rows number; l_sup_rows number;
  begin
    pkg_security.set_context('REP01');
    select count(distinct rep_user_id) into l_rep_rows from v_sec_visits;
    assert_true('SCOPE', 'BR-06 a representative sees exactly one rep''s visits',
                l_rep_rows <= 1, 'distinct reps visible: ' || l_rep_rows);

    pkg_security.set_context('SUP1');
    select count(distinct rep_user_id) into l_sup_rows from v_sec_visits;
    assert_true('SCOPE', 'BR-06 a supervisor sees the team, not one rep',
                l_sup_rows > 1, 'distinct reps visible: ' || l_sup_rows);

    pkg_security.set_context('MANAGER');
    select count(distinct rep_user_id) into l_mgr_rows from v_sec_visits;
    assert_true('SCOPE', 'BR-06 a manager sees more than a supervisor',
                l_mgr_rows > l_sup_rows,
                'manager ' || l_mgr_rows || ' vs supervisor ' || l_sup_rows);

    -- Negative: writing for a rep outside scope must be refused.
    declare
      l_other number;
      l_trx   number;
    begin
      pkg_security.set_context('REP01');
      select user_id into l_other from app_users where username = 'REP12';
      pkg_sample.receive(l_other, 1, 5, 'cross-scope write', l_trx);
      assert_raises('SCOPE', 'BR-06 writing outside scope is refused', 20002, null);
    exception
      when others then
        assert_raises('SCOPE', 'BR-06 writing outside scope is refused', 20002, sqlcode);
    end;

    pkg_security.set_context('MANAGER');
    rollback;
  end test_scoping;

