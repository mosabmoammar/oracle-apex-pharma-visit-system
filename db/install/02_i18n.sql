--------------------------------------------------------------------------------
-- Pharma Visit System — V2__bilingual_reference_data.sql
-- Adds Arabic/English pairs to reference data and the language resolution layer.
--
-- Why columns and not a generic translation table:
--   the language set is closed (2) and reference data is small. A generic
--   TRANSLATIONS table would add a join to every reference lookup, defeat
--   NOT NULL constraints on the name, and prevent a single covering index.
--   If the language set were open-ended, this decision would invert.
--
-- Prerequisite: database character set AL32UTF8.
--------------------------------------------------------------------------------
set define off

--------------------------------------------------------------------------------
-- 1. Verify character set before doing anything else
--------------------------------------------------------------------------------
declare
  l_charset varchar2(40);
begin
  select value into l_charset
    from nls_database_parameters
   where parameter = 'NLS_CHARACTERSET';

  if l_charset <> 'AL32UTF8' then
    raise_application_error(-20999,
      'Database character set is ' || l_charset ||
      '. Pharma Visit System requires AL32UTF8 for Arabic support.');
  end if;
end;
/

