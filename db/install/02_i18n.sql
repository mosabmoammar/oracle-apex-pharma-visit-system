-- 6. PKG_I18N — single point of language resolution
--------------------------------------------------------------------------------
create or replace package pkg_i18n as
  /**
   * Language resolution for data-layer labels.
   * UI chrome is translated through APEX Text Messages; this package covers
   * values that live in tables and therefore cannot be APEX-translated.
   */

  gc_default_lang constant varchar2(2) := 'en';

  -- Current language: session context first, APEX session second, default last.
  function current_lang return varchar2;

  -- Pick the right side of an EN/AR pair. DETERMINISTIC so it can be used
  -- in function-based indexes and is cached within a single SQL statement.
  function label (p_en in varchar2, p_ar in varchar2) return varchar2 deterministic;

  -- Bilingual message from the error catalogue.
  function message (p_error_code in number) return varchar2;

  -- Raise a catalogued error in the user's language.
  procedure raise_error (p_error_code in number, p_extra in varchar2 default null);

  -- Sort key that orders Arabic correctly and English naturally.
  function sort_key (p_en in varchar2, p_ar in varchar2) return raw deterministic;
end pkg_i18n;
/

create or replace package body pkg_i18n as

  function current_lang return varchar2 is
    l_lang varchar2(10);
  begin
    l_lang := sys_context('CTX_PVS','LANG');

    if l_lang is null then
      l_lang := substr(nvl(apex_util.get_session_lang, gc_default_lang), 1, 2);
    end if;

    return case when lower(l_lang) = 'ar' then 'ar' else gc_default_lang end;
  exception
    when others then
      return gc_default_lang;
  end current_lang;


  function label (p_en in varchar2, p_ar in varchar2) return varchar2 deterministic is
  begin
    return case when current_lang = 'ar' then nvl(p_ar, p_en) else nvl(p_en, p_ar) end;
  end label;


  function message (p_error_code in number) return varchar2 is
    l_msg error_messages%rowtype;
  begin
    select * into l_msg
      from error_messages
     where error_code = p_error_code;

    return label(l_msg.message_en, l_msg.message_ar);
  exception
    when no_data_found then
      return 'Unexpected error (' || p_error_code || ')';
  end message;


  procedure raise_error (p_error_code in number, p_extra in varchar2 default null) is
  begin
    raise_application_error(
      -p_error_code,
      message(p_error_code) || case when p_extra is not null then ' [' || p_extra || ']' end);
  end raise_error;


  function sort_key (p_en in varchar2, p_ar in varchar2) return raw deterministic is
  begin
    return case
             when current_lang = 'ar'
               then nlssort(nvl(p_ar, p_en), 'NLS_SORT=ARABIC')
             else nlssort(nvl(p_en, p_ar), 'NLS_SORT=BINARY_CI')
           end;
  end sort_key;

end pkg_i18n;
/

--------------------------------------------------------------------------------
-- 7. Bilingual lookup views — consumed directly by APEX LOVs
--------------------------------------------------------------------------------
create or replace view v_lov_domain as
select domain_code,
       value_code                            as return_value,
       pkg_i18n.label(label_en, label_ar)    as display_value,
       sort_order
  from domain_values
 where status = 'ACTIVE';

create or replace view v_lov_products as
select product_id                                              as return_value,
       pkg_i18n.label(product_name_en, product_name_ar)         as display_value,
       product_code
  from products
 where status = 'ACTIVE'
 order by pkg_i18n.sort_key(product_name_en, product_name_ar);

create or replace view v_lov_doctors as
select d.doctor_id                                             as return_value,
       pkg_i18n.label(d.full_name_en, d.full_name_ar) || ' — ' ||
       pkg_i18n.label(f.facility_name_en, f.facility_name_ar)  as display_value,
       d.tier,
       f.region_id
  from doctors d
  join facilities f on f.facility_id = d.facility_id
 where d.status = 'ACTIVE'
 order by pkg_i18n.sort_key(d.full_name_en, d.full_name_ar);

