create table products (
  product_id              number generated by default on null as identity
                          constraint products_pk primary key,
  product_code            varchar2(20)  not null,
  product_name            varchar2(160) not null,
  dosage_form             varchar2(40),
  strength                varchar2(40),
  default_monthly_ceiling number(10) default 0 not null,
  status                  varchar2(10) default 'ACTIVE' not null,
  created_by              varchar2(64) default coalesce(sys_context('APEX$SESSION','APP_USER'), user) not null,
  created_on              timestamp with local time zone default systimestamp not null,
  updated_by              varchar2(64),
  updated_on              timestamp with local time zone,
  constraint products_uk_code    unique (product_code),
  constraint products_ck_ceiling check (default_monthly_ceiling >= 0),
  constraint products_ck_status  check (status in ('ACTIVE','INACTIVE','SUSPENDED'))
);


create table product_batches (
  batch_id    number generated by default on null as identity
              constraint batches_pk primary key,
  product_id  number not null,
  batch_no    varchar2(40) not null,
  expiry_date date not null,
  status      varchar2(10) default 'ACTIVE' not null,
  created_on  timestamp with local time zone default systimestamp not null,
  constraint batches_uk1     unique (product_id, batch_no),
  constraint batches_fk_prod foreign key (product_id) references products (product_id),
  constraint batches_ck_stat check (status in ('ACTIVE','BLOCKED','WRITTEN_OFF'))
);
create index batches_ix1 on product_batches (expiry_date);


create table product_ceilings (
  ceiling_id      number generated by default on null as identity
                  constraint ceilings_pk primary key,
  product_id      number not null,
  doctor_tier     varchar2(1) not null,
  monthly_ceiling number(10)  not null,
  constraint ceilings_uk1     unique (product_id, doctor_tier),
  constraint ceilings_fk_prod foreign key (product_id) references products (product_id),
  constraint ceilings_ck_tier check (doctor_tier in ('A','B','C')),
  constraint ceilings_ck_qty  check (monthly_ceiling >= 0)
);

comment on table product_ceilings is 'Tier override of PRODUCTS.DEFAULT_MONTHLY_CEILING. Resolution order: exception > tier ceiling > product default.';

