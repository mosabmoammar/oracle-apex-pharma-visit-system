create table targets (
  target_id    number generated by default on null as identity
               constraint targets_pk primary key,
  rep_user_id  number not null,
  product_id   number not null,
  period_id    number not null,
  target_value number(12,2) not null,
  target_unit  varchar2(20) default 'VISITS' not null,
  created_by   varchar2(64) default coalesce(sys_context('APEX$SESSION','APP_USER'), user) not null,
  created_on   timestamp with local time zone default systimestamp not null,
  constraint targets_uk1     unique (rep_user_id, product_id, period_id),
  constraint targets_fk_rep  foreign key (rep_user_id) references app_users (user_id),
  constraint targets_fk_prod foreign key (product_id)  references products  (product_id),
  constraint targets_fk_per  foreign key (period_id)   references periods   (period_id),
  constraint targets_ck_val  check (target_value > 0),
  constraint targets_ck_unit check (target_unit in ('VISITS','SAMPLES','POINTS'))
);
create index targets_ix1 on targets (period_id, product_id);
create index targets_ix2 on targets (product_id);


create table achievement_snapshots (
  snapshot_id    number generated by default on null as identity
                 constraint achv_pk primary key,
  target_id      number not null,
  period_id      number not null,
  achieved_value number(12,2) default 0 not null,
  coverage_pct   number(5,2),
  calculated_on  timestamp with local time zone default systimestamp not null,
  constraint achv_uk1        unique (target_id, period_id),
  constraint achv_fk_target  foreign key (target_id) references targets (target_id),
  constraint achv_fk_period  foreign key (period_id) references periods (period_id),
  constraint achv_ck_cov     check (coverage_pct between 0 and 999.99)
);
create index achv_ix1 on achievement_snapshots (period_id);

