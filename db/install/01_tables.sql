create table visit_plans (
  plan_id       number generated by default on null as identity
                constraint plans_pk primary key,
  rep_user_id   number not null,
  period_id     number not null,
  status        varchar2(12) default 'DRAFT' not null,
  submitted_on  timestamp with local time zone,
  approved_by   number,
  approved_on   timestamp with local time zone,
  reject_reason varchar2(400),
  created_by    varchar2(64) default coalesce(sys_context('APEX$SESSION','APP_USER'), user) not null,
  created_on    timestamp with local time zone default systimestamp not null,
  updated_by    varchar2(64),
  updated_on    timestamp with local time zone,
  constraint plans_uk1        unique (rep_user_id, period_id),
  constraint plans_fk_rep     foreign key (rep_user_id) references app_users (user_id),
  constraint plans_fk_period  foreign key (period_id)   references periods   (period_id),
  constraint plans_fk_apprv   foreign key (approved_by) references app_users (user_id),
  constraint plans_ck_status  check (status in ('DRAFT','SUBMITTED','APPROVED','REJECTED')),
  constraint plans_ck_reject  check (status <> 'REJECTED' or reject_reason is not null)
);
create index plans_ix1 on visit_plans (period_id, status);
create index plans_ix2 on visit_plans (approved_by);


create table plan_items (
  plan_item_id  number generated by default on null as identity
                constraint plan_items_pk primary key,
  plan_id       number not null,
  doctor_id     number not null,
  planned_date  date   not null,
  planned_start timestamp with local time zone not null,
  planned_end   timestamp with local time zone not null,
  objective     varchar2(400),
  item_status   varchar2(12) default 'PLANNED' not null,
  constraint plan_items_fk_plan foreign key (plan_id)   references visit_plans (plan_id) on delete cascade,
  constraint plan_items_fk_doc  foreign key (doctor_id) references doctors     (doctor_id),
  constraint plan_items_ck_time check (planned_end > planned_start),
  constraint plan_items_ck_stat check (item_status in ('PLANNED','EXECUTED','MISSED','CANCELLED'))
);
create index plan_items_ix1 on plan_items (plan_id, planned_date);
create index plan_items_ix2 on plan_items (doctor_id);

