create table visits (
  visit_id      number generated by default on null as identity
                constraint visits_pk primary key,
  plan_item_id  number,
  rep_user_id   number not null,
  doctor_id     number not null,
  period_id     number not null,
  actual_start  timestamp with local time zone not null,
  actual_end    timestamp with local time zone not null,
  outcome       varchar2(15) not null,
  is_unplanned  varchar2(1) default 'N' not null,
  reason        varchar2(400),
  notes         clob,
  client_ref    varchar2(64),
  created_by    varchar2(64) default coalesce(sys_context('APEX$SESSION','APP_USER'), user) not null,
  created_on    timestamp with local time zone default systimestamp not null,
  updated_by    varchar2(64),
  updated_on    timestamp with local time zone,
  constraint visits_uk_item     unique (plan_item_id),
  constraint visits_uk_ref      unique (client_ref),
  constraint visits_fk_item     foreign key (plan_item_id) references plan_items (plan_item_id),
  constraint visits_fk_rep      foreign key (rep_user_id)  references app_users  (user_id),
  constraint visits_fk_doc      foreign key (doctor_id)    references doctors    (doctor_id),
  constraint visits_fk_period   foreign key (period_id)    references periods    (period_id),
  constraint visits_ck_time     check (actual_end > actual_start),
  constraint visits_ck_outcome  check (outcome in ('COMPLETED','NOT_AVAILABLE','POSTPONED','CANCELLED')),
  constraint visits_ck_unplan   check (is_unplanned in ('Y','N')),
  constraint visits_ck_reason   check (outcome = 'COMPLETED' or reason is not null),
  constraint visits_ck_unplan_r check (is_unplanned = 'N' or reason is not null)
);
create index visits_ix1 on visits (rep_user_id, actual_start);
create index visits_ix2 on visits (doctor_id, actual_start);
create index visits_ix3 on visits (period_id, outcome);

comment on column visits.client_ref  is 'Client-supplied idempotency key for offline sync. The unique constraint IS the deduplication.';
comment on column visits.plan_item_id is 'Null for unplanned visits; unique otherwise so one plan item yields at most one visit.';


create table visit_products (
  visit_product_id number generated by default on null as identity
                   constraint visit_prod_pk primary key,
  visit_id         number not null,
  product_id       number not null,
  feedback         varchar2(20),
  constraint visit_prod_uk1     unique (visit_id, product_id),
  constraint visit_prod_fk_vis  foreign key (visit_id)   references visits   (visit_id) on delete cascade,
  constraint visit_prod_fk_prod foreign key (product_id) references products (product_id),
  constraint visit_prod_ck_fb   check (feedback in ('POSITIVE','NEUTRAL','OBJECTION'))
);
create index visit_prod_ix1 on visit_products (product_id);

