create table regions (
  region_id         number generated by default on null as identity
                    constraint regions_pk primary key,
  parent_region_id  number,
  region_code       varchar2(20)  not null,
  region_name       varchar2(120) not null,
  region_level      varchar2(20)  default 'TERRITORY' not null,
  status            varchar2(10)  default 'ACTIVE'    not null,
  created_by        varchar2(64)  default coalesce(sys_context('APEX$SESSION','APP_USER'), user) not null,
  created_on        timestamp with local time zone default systimestamp not null,
  updated_by        varchar2(64),
  updated_on        timestamp with local time zone,
  constraint regions_uk_code   unique (region_code),
  constraint regions_fk_parent foreign key (parent_region_id) references regions (region_id),
  constraint regions_ck_level  check (region_level in ('COUNTRY','REGION','TERRITORY')),
  constraint regions_ck_status check (status in ('ACTIVE','INACTIVE'))
);
create index regions_ix1 on regions (parent_region_id);

comment on table  regions is 'Hierarchical geography: country > region > territory';
comment on column regions.region_level is 'Depth marker used to validate the hierarchy';


create table app_users (
  user_id       number generated by default on null as identity
                constraint app_users_pk primary key,
  username      varchar2(64)  not null,
  full_name     varchar2(160) not null,
  email         varchar2(160) not null,
  phone         varchar2(30),
  status        varchar2(10) default 'ACTIVE' not null,
  created_by    varchar2(64) default coalesce(sys_context('APEX$SESSION','APP_USER'), user) not null,
  created_on    timestamp with local time zone default systimestamp not null,
  updated_by    varchar2(64),
  updated_on    timestamp with local time zone,
  constraint app_users_uk_username unique (username),
  constraint app_users_uk_email    unique (email),
  constraint app_users_ck_status   check (status in ('ACTIVE','INACTIVE','LOCKED'))
);

comment on table app_users is 'Application accounts. Credentials are handled by the APEX authentication scheme, never stored here.';


create table roles (
  role_id     number generated by default on null as identity
              constraint roles_pk primary key,
  role_code   varchar2(30)  not null,
  role_name   varchar2(80)  not null,
  description varchar2(400),
  constraint roles_uk_code check (role_code = upper(role_code)) deferrable initially immediate,
  constraint roles_uk_role unique (role_code)
);

create table user_roles (
  user_role_id number generated by default on null as identity
               constraint user_roles_pk primary key,
  user_id      number not null,
  role_id      number not null,
  granted_on   date default trunc(sysdate) not null,
  constraint user_roles_uk1 unique (user_id, role_id),
  constraint user_roles_fk_user foreign key (user_id) references app_users (user_id),
  constraint user_roles_fk_role foreign key (role_id) references roles (role_id)
);
create index user_roles_ix1 on user_roles (role_id);


create table rep_assignments (
  assignment_id       number generated by default on null as identity
                      constraint rep_asg_pk primary key,
  rep_user_id         number not null,
  supervisor_user_id  number not null,
  region_id           number not null,
  valid_from          date   not null,
  valid_to            date,
  created_by          varchar2(64) default coalesce(sys_context('APEX$SESSION','APP_USER'), user) not null,
  created_on          timestamp with local time zone default systimestamp not null,
  constraint rep_asg_fk_rep    foreign key (rep_user_id)        references app_users (user_id),
  constraint rep_asg_fk_sup    foreign key (supervisor_user_id) references app_users (user_id),
  constraint rep_asg_fk_region foreign key (region_id)          references regions   (region_id),
  constraint rep_asg_ck_dates  check (valid_to is null or valid_to > valid_from),
  constraint rep_asg_ck_self   check (rep_user_id <> supervisor_user_id)
);
create index rep_asg_ix1 on rep_assignments (rep_user_id, valid_from);
create index rep_asg_ix2 on rep_assignments (supervisor_user_id);
create index rep_asg_ix3 on rep_assignments (region_id);

comment on table rep_assignments is 'Temporal reporting line. Overlap is enforced in PKG_SECURITY: Oracle has no range-exclusion constraint.';

