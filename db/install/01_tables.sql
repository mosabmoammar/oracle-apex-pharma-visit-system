create table facilities (
  facility_id   number generated by default on null as identity
                constraint facilities_pk primary key,
  region_id     number not null,
  facility_code varchar2(20)  not null,
  facility_name varchar2(160) not null,
  facility_type varchar2(20)  not null,
  address_line  varchar2(300),
  status        varchar2(10) default 'ACTIVE' not null,
  created_by    varchar2(64) default coalesce(sys_context('APEX$SESSION','APP_USER'), user) not null,
  created_on    timestamp with local time zone default systimestamp not null,
  updated_by    varchar2(64),
  updated_on    timestamp with local time zone,
  constraint facilities_uk_code unique (facility_code),
  constraint facilities_fk_reg  foreign key (region_id) references regions (region_id),
  constraint facilities_ck_type check (facility_type in ('HOSPITAL','CLINIC','PHARMACY','CENTER')),
  constraint facilities_ck_stat check (status in ('ACTIVE','INACTIVE'))
);
create index facilities_ix1 on facilities (region_id);


create table doctors (
  doctor_id   number generated by default on null as identity
              constraint doctors_pk primary key,
  facility_id number not null,
  doctor_code varchar2(20)  not null,
  full_name   varchar2(160) not null,
  specialty   varchar2(80)  not null,
  tier        varchar2(1)   default 'C' not null,
  phone       varchar2(30),
  status      varchar2(10)  default 'ACTIVE' not null,
  created_by  varchar2(64) default coalesce(sys_context('APEX$SESSION','APP_USER'), user) not null,
  created_on  timestamp with local time zone default systimestamp not null,
  updated_by  varchar2(64),
  updated_on  timestamp with local time zone,
  constraint doctors_uk_code unique (doctor_code),
  constraint doctors_fk_fac  foreign key (facility_id) references facilities (facility_id),
  constraint doctors_ck_tier check (tier in ('A','B','C')),
  constraint doctors_ck_stat check (status in ('ACTIVE','INACTIVE'))
);
create index doctors_ix1 on doctors (facility_id);
create index doctors_ix2 on doctors (specialty, tier);

comment on column doctors.tier is 'Commercial classification driving visit frequency targets and sample ceilings';

