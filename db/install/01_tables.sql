create table periods (
  period_id    number generated by default on null as identity
               constraint periods_pk primary key,
  period_year  number(4) not null,
  period_month number(2) not null,
  start_date   date not null,
  end_date     date not null,
  status       varchar2(10) default 'OPEN' not null,
  closed_by    varchar2(64),
  closed_on    timestamp with local time zone,
  constraint periods_uk1      unique (period_year, period_month),
  constraint periods_ck_month check (period_month between 1 and 12),
  constraint periods_ck_dates check (end_date >= start_date),
  constraint periods_ck_stat  check (status in ('OPEN','CLOSED'))
);

comment on table periods is 'Single gate for immutability: every write API validates the period is OPEN.';

