create table audit_log (
  audit_id    number generated by default on null as identity
              constraint audit_pk primary key,
  table_name  varchar2(60) not null,
  record_id   number,
  action      varchar2(10) not null,
  old_values  clob,
  new_values  clob,
  changed_by  varchar2(64) default coalesce(sys_context('APEX$SESSION','APP_USER'), user) not null,
  changed_on  timestamp with local time zone default systimestamp not null,
  constraint audit_ck_action check (action in ('INSERT','UPDATE','DELETE')),
  constraint audit_ck_oldjson check (old_values is null or old_values is json),
  constraint audit_ck_newjson check (new_values is null or new_values is json)
);
create index audit_ix1 on audit_log (table_name, record_id);
create index audit_ix2 on audit_log (changed_on);

comment on table audit_log is 'Generic audit sink. Row images stored as JSON so adding a table to audit scope needs no schema change.';


create table error_messages (
  error_code  number(5) not null
              constraint errmsg_pk primary key,
  message_en  varchar2(400) not null,
  message_ar  varchar2(400) not null,
  constraint errmsg_ck_range check (error_code between 20000 and 20999)
);

comment on table error_messages is 'Central catalogue for RAISE_APPLICATION_ERROR, surfaced through a custom APEX error handler in both languages.';

