create table sample_transactions (
  trx_id       number generated by default on null as identity
               constraint sample_trx_pk primary key,
  rep_user_id  number not null,
  batch_id     number not null,
  visit_id     number,
  doctor_id    number,
  period_id    number not null,
  trx_type     varchar2(20) not null,
  quantity     number(10)   not null,
  trx_date     timestamp with local time zone default systimestamp not null,
  reference    varchar2(200),
  client_ref   varchar2(64),
  created_by   varchar2(64) default coalesce(sys_context('APEX$SESSION','APP_USER'), user) not null,
  constraint sample_trx_uk_ref   unique (client_ref),
  constraint sample_trx_fk_rep   foreign key (rep_user_id) references app_users       (user_id),
  constraint sample_trx_fk_batch foreign key (batch_id)    references product_batches (batch_id),
  constraint sample_trx_fk_vis   foreign key (visit_id)    references visits          (visit_id),
  constraint sample_trx_fk_doc   foreign key (doctor_id)   references doctors         (doctor_id),
  constraint sample_trx_fk_per   foreign key (period_id)   references periods         (period_id),
  constraint sample_trx_ck_type  check (trx_type in ('RECEIPT','DISPENSE','RETURN','ADJUSTMENT','EXPIRY_WRITE_OFF')),
  constraint sample_trx_ck_qty   check (quantity <> 0),
  constraint sample_trx_ck_disp  check (trx_type <> 'DISPENSE' or (visit_id is not null and doctor_id is not null))
);
create index sample_trx_ix1 on sample_transactions (rep_user_id, batch_id, trx_date);
create index sample_trx_ix2 on sample_transactions (visit_id);
create index sample_trx_ix3 on sample_transactions (doctor_id, period_id);
create index sample_trx_ix4 on sample_transactions (batch_id);
create index sample_trx_ix5 on sample_transactions (period_id);

comment on table  sample_transactions is 'Immutable ledger. Corrections are reversing entries, never updates or deletes.';
comment on column sample_transactions.quantity is 'Signed: positive increases stock (RECEIPT), negative decreases it (DISPENSE, WRITE_OFF).';


create table sample_balances (
  balance_id       number generated by default on null as identity
                   constraint sample_bal_pk primary key,
  rep_user_id      number not null,
  batch_id         number not null,
  quantity_on_hand number(10) default 0 not null,
  last_movement_on timestamp with local time zone,
  constraint sample_bal_uk1     unique (rep_user_id, batch_id),
  constraint sample_bal_fk_rep  foreign key (rep_user_id) references app_users       (user_id),
  constraint sample_bal_fk_bat  foreign key (batch_id)    references product_batches (batch_id),
  constraint sample_bal_ck_qty  check (quantity_on_hand >= 0)
);
create index sample_bal_ix1 on sample_balances (batch_id);

comment on table sample_balances is 'Maintained aggregate updated in the same transaction as the ledger entry; a nightly job reconciles it against SAMPLE_TRANSACTIONS.';


create table sample_exceptions (
  exception_id    number generated by default on null as identity
                  constraint sample_exc_pk primary key,
  doctor_id       number not null,
  product_id      number not null,
  period_id       number not null,
  extra_allowance number(10) not null,
  reason          varchar2(400) not null,
  approved_by     number not null,
  approved_on     timestamp with local time zone default systimestamp not null,
  constraint sample_exc_uk1     unique (doctor_id, product_id, period_id),
  constraint sample_exc_fk_doc  foreign key (doctor_id)   references doctors   (doctor_id),
  constraint sample_exc_fk_prod foreign key (product_id)  references products  (product_id),
  constraint sample_exc_fk_per  foreign key (period_id)   references periods   (period_id),
  constraint sample_exc_fk_appr foreign key (approved_by) references app_users (user_id),
  constraint sample_exc_ck_qty  check (extra_allowance > 0)
);
create index sample_exc_ix1 on sample_exceptions (product_id);
create index sample_exc_ix2 on sample_exceptions (period_id);
create index sample_exc_ix3 on sample_exceptions (approved_by);

