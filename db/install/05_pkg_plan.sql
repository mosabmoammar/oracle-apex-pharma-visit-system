create or replace package pkg_plan as

  gc_status_draft     constant varchar2(12) := 'DRAFT';
  gc_status_submitted constant varchar2(12) := 'SUBMITTED';
  gc_status_approved  constant varchar2(12) := 'APPROVED';
  gc_status_rejected  constant varchar2(12) := 'REJECTED';

  -- Minimum visits per month for a tier A doctor (advisory, not blocking).
  gc_tier_a_min_visits constant number := 2;

  function get_or_create_plan (
    p_rep_user_id in number,
    p_period_id   in number) return number;

  procedure add_item (
    p_plan_id       in  number,
    p_doctor_id     in  number,
    p_planned_start in  timestamp with local time zone,
    p_planned_end   in  timestamp with local time zone,
    p_objective     in  varchar2 default null,
    p_plan_item_id  out number);

  procedure remove_item (p_plan_item_id in number);

  procedure submit  (p_plan_id in number);
  procedure approve (p_plan_id in number, p_note in varchar2 default null);
  procedure reject  (p_plan_id in number, p_reason in varchar2);

  -- Change requests against an approved plan
  procedure request_change (
    p_plan_id       in  number,
    p_request_type  in  varchar2,
    p_reason        in  varchar2,
    p_plan_item_id  in  number   default null,
    p_doctor_id     in  number   default null,
    p_planned_start in  timestamp with local time zone default null,
    p_planned_end   in  timestamp with local time zone default null,
    p_request_id    out number);

  procedure decide_change (
    p_request_id in number,
    p_approve    in boolean,
    p_note       in varchar2 default null);

  -- Advisory coverage check surfaced on the plan page
  function tier_a_coverage_gap (p_plan_id in number) return number;

  -- Marks unexecuted items as MISSED at period close
  procedure close_period_plans (p_period_id in number, p_missed out number);

end pkg_plan;
/

--------------------------------------------------------------------------------
-- Package body
--------------------------------------------------------------------------------
create or replace package body pkg_plan as

  ------------------------------------------------------------------
  -- Private: load plan and enforce read/write scope
  ------------------------------------------------------------------
  function load_plan (p_plan_id in number, p_lock in boolean default false)
    return visit_plans%rowtype is
    l_plan visit_plans%rowtype;
  begin
    if p_lock then
      select * into l_plan from visit_plans where plan_id = p_plan_id for update;
    else
      select * into l_plan from visit_plans where plan_id = p_plan_id;
    end if;

    pkg_security.assert_can_write_rep(l_plan.rep_user_id);
    return l_plan;
  exception
    when no_data_found then
      pkg_i18n.raise_error(20002, 'plan_id=' || p_plan_id);
  end load_plan;

  ------------------------------------------------------------------
  procedure assert_period_open (p_period_id in number) is
    l_status varchar2(10);
  begin
    select status into l_status from periods where period_id = p_period_id;
    if l_status <> 'OPEN' then
      pkg_i18n.raise_error(20003);
    end if;
  end assert_period_open;

  ------------------------------------------------------------------
  -- Private: overlap test across BOTH planned items and executed visits.
  -- Two intervals overlap when each begins before the other ends.
  ------------------------------------------------------------------
  procedure assert_no_overlap (
    p_rep_user_id  in number,
    p_start        in timestamp with local time zone,
    p_end          in timestamp with local time zone,
    p_plan_item_id in number default null) is
    l_cnt number;
  begin
    if p_end <= p_start then
      pkg_i18n.raise_error(20015, 'end <= start');
    end if;

    select count(*)
      into l_cnt
      from (
        select pi.plan_item_id as id, pi.planned_start as s, pi.planned_end as e
          from plan_items pi
          join visit_plans pl on pl.plan_id = pi.plan_id
         where pl.rep_user_id = p_rep_user_id
           and pi.item_status in ('PLANNED','EXECUTED')
           and pl.status <> 'REJECTED'
        union all
        select null, v.actual_start, v.actual_end
          from visits v
         where v.rep_user_id = p_rep_user_id
           and v.outcome <> 'CANCELLED')
     where (p_plan_item_id is null or id is null or id <> p_plan_item_id)
       and s < p_end
       and e > p_start;

    if l_cnt > 0 then
      pkg_i18n.raise_error(20015);
    end if;
  end assert_no_overlap;

  ------------------------------------------------------------------
  function get_or_create_plan (p_rep_user_id in number, p_period_id in number)
    return number is
    l_plan_id number;
  begin
    pkg_security.assert_can_write_rep(p_rep_user_id);
    assert_period_open(p_period_id);

    begin
      select plan_id into l_plan_id
        from visit_plans
       where rep_user_id = p_rep_user_id
         and period_id   = p_period_id;
    exception
      when no_data_found then
        insert into visit_plans (rep_user_id, period_id, status)
             values (p_rep_user_id, p_period_id, gc_status_draft)
          returning plan_id into l_plan_id;
    end;

    return l_plan_id;
  end get_or_create_plan;

  ------------------------------------------------------------------
  procedure add_item (
    p_plan_id       in  number,
    p_doctor_id     in  number,
    p_planned_start in  timestamp with local time zone,
    p_planned_end   in  timestamp with local time zone,
    p_objective     in  varchar2 default null,
    p_plan_item_id  out number) is
    l_plan visit_plans%rowtype;
    l_lock number;
  begin
    l_plan := load_plan(p_plan_id);
    assert_period_open(l_plan.period_id);

    if l_plan.status <> gc_status_draft then
      pkg_i18n.raise_error(20013);
    end if;

    -- Serialise all schedule writes for this representative. Without this,
    -- two concurrent sessions both pass the overlap check and both insert.
    select user_id into l_lock
      from app_users
     where user_id = l_plan.rep_user_id
       for update;

    assert_no_overlap(l_plan.rep_user_id, p_planned_start, p_planned_end);

    insert into plan_items (plan_id, doctor_id, planned_date, planned_start, planned_end, objective)
         values (p_plan_id, p_doctor_id, trunc(cast(p_planned_start as date)),
                 p_planned_start, p_planned_end, p_objective)
      returning plan_item_id into p_plan_item_id;
  end add_item;

  ------------------------------------------------------------------
  procedure remove_item (p_plan_item_id in number) is
    l_plan_id number;
    l_plan    visit_plans%rowtype;
    l_status  varchar2(12);
  begin
    select pi.plan_id, pi.item_status
      into l_plan_id, l_status
      from plan_items pi
     where pi.plan_item_id = p_plan_item_id;

    l_plan := load_plan(l_plan_id);

    if l_plan.status <> gc_status_draft then
      pkg_i18n.raise_error(20013);
    end if;

    if l_status = 'EXECUTED' then
      pkg_i18n.raise_error(20014, 'item already executed');
    end if;

    delete from plan_items where plan_item_id = p_plan_item_id;
  end remove_item;

  ------------------------------------------------------------------
  function tier_a_coverage_gap (p_plan_id in number) return number is
    l_gap number;
  begin
    -- Tier A doctors in the rep's territories that are planned fewer than
    -- the required number of times this month.
    select count(*)
      into l_gap
      from (
        select d.doctor_id, count(pi.plan_item_id) as planned_count
          from visit_plans pl
          join rep_assignments a
            on a.rep_user_id = pl.rep_user_id
           and trunc(sysdate) between a.valid_from and nvl(a.valid_to, date '4000-01-01')
          join facilities f on f.region_id  = a.region_id
          join doctors    d on d.facility_id = f.facility_id
                           and d.tier = 'A'
                           and d.status = 'ACTIVE'
          left join plan_items pi
            on pi.plan_id = pl.plan_id
           and pi.doctor_id = d.doctor_id
         where pl.plan_id = p_plan_id
         group by d.doctor_id
        having count(pi.plan_item_id) < gc_tier_a_min_visits);

    return l_gap;
  end tier_a_coverage_gap;

  ------------------------------------------------------------------
  procedure submit (p_plan_id in number) is
    l_plan  visit_plans%rowtype;
    l_items number;
  begin
    l_plan := load_plan(p_plan_id, p_lock => true);
    assert_period_open(l_plan.period_id);

    if l_plan.status <> gc_status_draft then
      pkg_i18n.raise_error(20014, l_plan.status);
    end if;

    select count(*) into l_items from plan_items where plan_id = p_plan_id;
    if l_items = 0 then
      pkg_i18n.raise_error(20014, 'empty plan');
    end if;

    update visit_plans
       set status       = gc_status_submitted,
           submitted_on = systimestamp,
           updated_by   = pkg_security.current_username,
           updated_on   = systimestamp
     where plan_id = p_plan_id;
  end submit;

  ------------------------------------------------------------------
  procedure approve (p_plan_id in number, p_note in varchar2 default null) is
    l_plan visit_plans%rowtype;
  begin
    if pkg_security.has_role(pkg_security.gc_role_supervisor) = 'N'
       and not pkg_security.is_privileged then
      pkg_i18n.raise_error(20002, 'approval requires supervisor role');
    end if;

    l_plan := load_plan(p_plan_id, p_lock => true);
    assert_period_open(l_plan.period_id);

    if l_plan.status <> gc_status_submitted then
      pkg_i18n.raise_error(20014, l_plan.status);
    end if;

    update visit_plans
       set status      = gc_status_approved,
           approved_by = pkg_security.current_user_id,
           approved_on = systimestamp,
           updated_by  = pkg_security.current_username,
           updated_on  = systimestamp
     where plan_id = p_plan_id;
  end approve;

  ------------------------------------------------------------------
  procedure reject (p_plan_id in number, p_reason in varchar2) is
    l_plan visit_plans%rowtype;
  begin
    if trim(p_reason) is null then
      pkg_i18n.raise_error(20016);
    end if;

    if pkg_security.has_role(pkg_security.gc_role_supervisor) = 'N'
       and not pkg_security.is_privileged then
      pkg_i18n.raise_error(20002, 'rejection requires supervisor role');
    end if;

    l_plan := load_plan(p_plan_id, p_lock => true);

    if l_plan.status <> gc_status_submitted then
      pkg_i18n.raise_error(20014, l_plan.status);
    end if;

    -- Rejection returns the plan to DRAFT so the rep can correct it,
    -- while the reason is preserved for the audit trail.
    update visit_plans
       set status        = gc_status_draft,
           reject_reason = p_reason,
           submitted_on  = null,
           updated_by    = pkg_security.current_username,
           updated_on    = systimestamp
     where plan_id = p_plan_id;
  end reject;

  ------------------------------------------------------------------
  procedure request_change (
    p_plan_id       in  number,
    p_request_type  in  varchar2,
    p_reason        in  varchar2,
    p_plan_item_id  in  number   default null,
    p_doctor_id     in  number   default null,
    p_planned_start in  timestamp with local time zone default null,
    p_planned_end   in  timestamp with local time zone default null,
    p_request_id    out number) is
    l_plan visit_plans%rowtype;
  begin
    if trim(p_reason) is null then
      pkg_i18n.raise_error(20016);
    end if;

    l_plan := load_plan(p_plan_id);
    assert_period_open(l_plan.period_id);

    if l_plan.status <> gc_status_approved then
      pkg_i18n.raise_error(20014, 'change requests apply to approved plans only');
    end if;

    -- Validate the proposed schedule now, so an approver never approves
    -- something that will fail on application.
    if p_request_type in ('ADD','RESCHEDULE') then
      assert_no_overlap(l_plan.rep_user_id, p_planned_start, p_planned_end, p_plan_item_id);
    end if;

    insert into plan_change_requests (
      plan_id, requested_by, request_type, plan_item_id, doctor_id,
      planned_date, planned_start, planned_end, reason)
    values (
      p_plan_id, pkg_security.current_user_id, p_request_type, p_plan_item_id, p_doctor_id,
      trunc(cast(p_planned_start as date)), p_planned_start, p_planned_end, p_reason)
    returning request_id into p_request_id;
  end request_change;

  ------------------------------------------------------------------
  procedure decide_change (
    p_request_id in number,
    p_approve    in boolean,
    p_note       in varchar2 default null) is
    l_req  plan_change_requests%rowtype;
    l_plan visit_plans%rowtype;
    l_new  number;
  begin
    if pkg_security.has_role(pkg_security.gc_role_supervisor) = 'N'
       and not pkg_security.is_privileged then
      pkg_i18n.raise_error(20002, 'decision requires supervisor role');
    end if;

    select * into l_req
      from plan_change_requests
     where request_id = p_request_id
       for update;

    if l_req.status <> 'PENDING' then
      pkg_i18n.raise_error(20014, l_req.status);
    end if;

    l_plan := load_plan(l_req.plan_id);
    assert_period_open(l_plan.period_id);

    if p_approve then
      -- Re-validate at application time: the schedule may have changed
      -- between request and decision.
      case l_req.request_type
        when 'ADD' then
          assert_no_overlap(l_plan.rep_user_id, l_req.planned_start, l_req.planned_end);
          insert into plan_items (plan_id, doctor_id, planned_date, planned_start, planned_end, objective)
               values (l_req.plan_id, l_req.doctor_id, l_req.planned_date,
                       l_req.planned_start, l_req.planned_end, l_req.reason)
            returning plan_item_id into l_new;

        when 'REMOVE' then
          update plan_items
             set item_status = 'CANCELLED'
           where plan_item_id = l_req.plan_item_id
             and item_status = 'PLANNED';

        when 'RESCHEDULE' then
          assert_no_overlap(l_plan.rep_user_id, l_req.planned_start, l_req.planned_end, l_req.plan_item_id);
          update plan_items
             set planned_date  = l_req.planned_date,
                 planned_start = l_req.planned_start,
                 planned_end   = l_req.planned_end
           where plan_item_id = l_req.plan_item_id
             and item_status = 'PLANNED';
      end case;
    end if;

    update plan_change_requests
       set status        = case when p_approve then 'APPROVED' else 'REJECTED' end,
           decided_by    = pkg_security.current_user_id,
           decided_on    = systimestamp,
           decision_note = p_note
     where request_id = p_request_id;
  end decide_change;

  ------------------------------------------------------------------
  procedure close_period_plans (p_period_id in number, p_missed out number) is
  begin
    if not pkg_security.is_privileged then
      pkg_i18n.raise_error(20002, 'period close requires manager role');
    end if;

    update plan_items pi
       set pi.item_status = 'MISSED'
     where pi.item_status = 'PLANNED'
       and exists (select 1
                     from visit_plans pl
                    where pl.plan_id = pi.plan_id
                      and pl.period_id = p_period_id);

    p_missed := sql%rowcount;

    update periods
       set status    = 'CLOSED',
           closed_by = pkg_security.current_username,
           closed_on = systimestamp
     where period_id = p_period_id;
  end close_period_plans;

end pkg_plan;
