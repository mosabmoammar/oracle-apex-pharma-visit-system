-- Pharma Visit System — 05_pkg_plan.sql
-- Monthly visit plan: state machine, overlap prevention, approval, change requests.
--
-- Why a state machine and not status flags
--   Statuses set by UPDATE statements scattered across pages drift within weeks.
--   Every transition here passes through one procedure that validates the
--   source state, the actor's role and the period. An illegal transition is
--   impossible to reach, not merely discouraged.
--
--     DRAFT ──submit──► SUBMITTED ──approve──► APPROVED
--       ▲                   │                     │
--       └────── reject ─────┘                     │
--       └──────────── change request ─────────────┘
--------------------------------------------------------------------------------
